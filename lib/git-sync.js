/**
 * Git-based project sync over an existing SSH/HTTP remote.
 *
 * The plugin deliberately does not host a Git daemon. The "host" is the device
 * that owns/points at the remote (for example an SSH bare repository); peers use
 * the same remote. This keeps authentication and network exposure in Git/SSH,
 * where operators already know how to manage them.
 *
 * Network settings are device-local (`.sync/config.json`) and are excluded from
 * the sync repository. Nothing runs unless `enabled` is explicitly set.
 */

import { spawn } from 'node:child_process';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import { URL } from 'node:url';

export const SYNC_PATHS = Object.freeze([
  'knowledge',
  'archive',
  'decisions',
  'snapshots',
  'staging',
  'contexts',
  'sessions',
]);

export const SYNC_DEFAULTS = Object.freeze({
  enabled: false,
  role: 'peer',
  remote: '',
  group: '',
  paths: ['knowledge', 'archive', 'decisions', 'snapshots'],
});

const SYNC_DIR = '.sync';
const CONFIG_FILE = 'config.json';
const GIT_TIMEOUT_MS = 30000;

function runGit(root, args, options = {}) {
  return new Promise((resolve) => {
    let child;
    try {
      child = spawn('git', args, {
        cwd: root,
        windowsHide: true,
        stdio: ['ignore', 'pipe', 'pipe'],
      });
    } catch (error) {
      resolve({ ok: false, code: -1, stdout: '', stderr: String(error?.message ?? error) });
      return;
    }
    let stdout = '';
    let stderr = '';
    let settled = false;
    const timer = setTimeout(() => {
      if (settled) return;
      settled = true;
      try { child.kill(); } catch { /* ignore */ }
      resolve({ ok: false, code: -1, stdout, stderr: `${stderr}\n操作超时（${GIT_TIMEOUT_MS}ms）`.trim() });
    }, options.timeoutMs ?? GIT_TIMEOUT_MS);
    child.stdout.on('data', (chunk) => { stdout += chunk.toString(); });
    child.stderr.on('data', (chunk) => { stderr += chunk.toString(); });
    child.on('error', (error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve({
        ok: false,
        code: -1,
        stdout,
        stderr: error?.code === 'ENOENT'
          ? (fs.existsSync(root) ? '找不到 git 命令：请先安装 Git，并加入 PATH' : '记忆根目录不存在')
          : String(error?.message ?? error),
      });
    });
    child.on('close', (code) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve({ ok: code === 0, code: code ?? -1, stdout, stderr });
    });
  });
}

function normalizePaths(value) {
  const list = Array.isArray(value) ? value : [];
  const picked = list.filter((item) => SYNC_PATHS.includes(item));
  return [...new Set(picked)];
}

export function syncConfigPath(root) {
  return path.join(path.resolve(root), SYNC_DIR, CONFIG_FILE);
}

export function readSyncConfig(root) {
  const file = syncConfigPath(root);
  let data = {};
  try {
    data = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    data = {};
  }
  return {
    enabled: data.enabled === true,
    role: data.role === 'host' ? 'host' : 'peer',
    remote: typeof data.remote === 'string' ? data.remote.trim() : '',
    group: typeof data.group === 'string' ? data.group.trim().slice(0, 120) : '',
    paths: normalizePaths(data.paths).length > 0
      ? normalizePaths(data.paths)
      : [...SYNC_DEFAULTS.paths],
  };
}

export function writeSyncConfig(root, patch = {}) {
  const current = readSyncConfig(root);
  const next = {
    enabled: patch.enabled === undefined ? current.enabled : patch.enabled === true,
    role: patch.role === 'host' ? 'host' : (patch.role === 'peer' ? 'peer' : current.role),
    remote: patch.remote === undefined ? current.remote : String(patch.remote).trim(),
    group: patch.group === undefined ? current.group : String(patch.group).trim().slice(0, 120),
    paths: patch.paths === undefined ? current.paths : normalizePaths(patch.paths),
  };
  if (next.paths.length === 0) next.paths = [...SYNC_DEFAULTS.paths];
  fs.mkdirSync(path.dirname(syncConfigPath(root)), { recursive: true });
  fs.writeFileSync(syncConfigPath(root), `${JSON.stringify(next, null, 2)}\n`, 'utf8');
  return next;
}

/** Git exclude rules: only the selected top-level layers are shareable. */
function excludeRules(paths) {
  const rules = [
    '# AI for Memory sync: generated by the plugin; do not commit this file.',
    '*',
    '!.gitattributes',
    '!.gitignore',
    '!/.sync/',
  ];
  for (const top of paths) {
    rules.push(`!${top}/`);
    rules.push(`!${top}/**`);
  }
  rules.push('**/_usage.json');
  rules.push('**/rag/');
  rules.push('**/knowledge.sqlite');
  rules.push('**/knowledge.sqlite-*');
  rules.push('**/compaction_status.json');
  rules.push('exports/');
  rules.push('.sync/');
  return rules.join('\n') + '\n';
}

function sameRoot(left, right) {
  const canonical = (value) => {
    try {
      return fs.realpathSync.native(value);
    } catch {
      return path.resolve(value);
    }
  };
  const a = canonical(left);
  const b = canonical(right);
  if (a === b) return true;
  return process.platform === 'win32' && a.toLowerCase() === b.toLowerCase();
}

const EXCLUDE_BEGIN = '# >>> AI for Memory sync >>>';
const EXCLUDE_END = '# <<< AI for Memory sync <<<';

/** Keep user-owned exclude rules; replace only our marked block. */
function writeSyncExclude(file, paths) {
  let current = '';
  try {
    current = fs.readFileSync(file, 'utf8');
  } catch {
    current = '';
  }
  const start = current.indexOf(EXCLUDE_BEGIN);
  const end = start >= 0 ? current.indexOf(EXCLUDE_END, start) : -1;
  if (start >= 0 && end >= start) {
    current = current.slice(0, start) + current.slice(end + EXCLUDE_END.length);
  }
  const prefix = current.trim() === '' ? '' : `${current.trimEnd()}\n\n`;
  const block = `${EXCLUDE_BEGIN}\n${excludeRules(paths)}${EXCLUDE_END}\n`;
  fs.writeFileSync(file, `${prefix}${block}`, 'utf8');
}

/** Ignore a nested memory repository in the parent project, without touching
 * the tracked `.gitignore`. This keeps `git add .` in the project from recording
 * the memory directory as an embedded git repository. */
async function ignoreNestedRepo(parentTop, memoryRoot) {
  const rel = path.relative(parentTop, memoryRoot).split(path.sep).join('/');
  if (rel === '' || rel.startsWith('..') || path.isAbsolute(rel)) return;
  const gitPath = await runGit(parentTop, ['rev-parse', '--git-path', 'info/exclude']);
  if (!gitPath.ok) return;
  const file = path.resolve(parentTop, gitPath.stdout.trim());
  let current = '';
  try {
    current = fs.readFileSync(file, 'utf8');
  } catch {
    current = '';
  }
  const entry = `/${rel}/`;
  if (current.split(/\r?\n/).some((line) => line.trim() === entry)) return;
  const prefix = current.trim() === '' ? '' : `${current.trimEnd()}\n`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${prefix}${entry}\n`, 'utf8');
}

async function ensureRepo(root, config) {
  for (const dir of [root, path.join(root, SYNC_DIR)]) fs.mkdirSync(dir, { recursive: true });
  const excludeFile = path.join(root, '.git', 'info', 'exclude');
  // `rev-parse --is-inside-work-tree` is true inside the user's project repo
  // too, which would make this sync feature stage and commit unrelated project
  // files. Require a repository whose top level is exactly the memory root.
  const top = await runGit(root, ['rev-parse', '--show-toplevel']);
  const ownRepo = top.ok && sameRoot(top.stdout.trim(), root);
  if (!ownRepo) {
    if (top.ok && top.stdout.trim() !== '') {
      await ignoreNestedRepo(top.stdout.trim(), root);
    }
    const init = await runGit(root, ['init']);
    if (!init.ok) return { ok: false, error: init.stderr || 'git init 失败' };
  }
  const excludeDir = path.dirname(excludeFile);
  try {
    fs.mkdirSync(excludeDir, { recursive: true });
    writeSyncExclude(excludeFile, config.paths);
  } catch (error) {
    return { ok: false, error: `无法写入 Git exclude：${String(error?.message ?? error)}` };
  }
  // Do not overwrite an identity the user already configured for this repo.
  const name = await runGit(root, ['config', '--get', 'user.name']);
  if (!name.ok || name.stdout.trim() === '') {
    await runGit(root, ['config', 'user.name', 'AI for Memory']);
  }
  const email = await runGit(root, ['config', '--get', 'user.email']);
  if (!email.ok || email.stdout.trim() === '') {
    await runGit(root, ['config', 'user.email', 'ai-for-memory@localhost']);
  }
  if (config.remote !== '') {
    const current = await runGit(root, ['remote', 'get-url', 'origin']);
    if (!current.ok || current.stdout.trim() !== config.remote) {
      const set = current.ok
        ? await runGit(root, ['remote', 'set-url', 'origin', config.remote])
        : await runGit(root, ['remote', 'add', 'origin', config.remote]);
      if (!set.ok) return { ok: false, error: set.stderr || '设置 git remote 失败' };
    }
  }
  return { ok: true };
}

function requireEnabled(config) {
  if (config.enabled !== true) return '网络同步未启用：先在面板打开并保存同步设置。';
  if (config.remote === '') return '没有配置主机 remote：请填写 SSH/HTTP Git 地址。';
  return '';
}

/** Current repository + remote state, without modifying anything. */
export async function syncStatus(root) {
  const config = readSyncConfig(root);
  const version = await runGit(root, ['--version']);
  const base = {
    config,
    gitAvailable: version.ok,
    gitVersion: version.ok ? version.stdout.trim() : '',
    initialized: false,
    remote: config.remote,
    branch: '',
    dirty: 0,
    staged: 0,
    ahead: 0,
    behind: 0,
    lastCommit: null,
    error: '',
  };
  if (!version.ok) return { ...base, error: 'Git 不可用' };
  const top = await runGit(root, ['rev-parse', '--show-toplevel']);
  if (!top.ok || !sameRoot(top.stdout.trim(), root)) return base;
  const status = await runGit(root, ['status', '--porcelain=v1']);
  const branch = await runGit(root, ['branch', '--show-current']);
  const log = await runGit(root, ['log', '-1', '--format=%h%x00%s%x00%an%x00%cI']);
  const remote = await runGit(root, ['remote', 'get-url', 'origin']);
  const dirty = status.ok
    ? status.stdout.split(/\r?\n/).filter((line) => line.trim() !== '').length
    : 0;
  const staged = status.ok
    ? status.stdout.split(/\r?\n/).filter((line) => /^[MADRC]/.test(line)).length
    : 0;
  let lastCommit = null;
  if (log.ok && log.stdout.trim() !== '') {
    const [hash, subject, author, at] = log.stdout.trim().split('\0');
    lastCommit = { hash, subject, author, at };
  }
  return {
    ...base,
    initialized: true,
    branch: branch.ok ? branch.stdout.trim() : '',
    dirty,
    staged,
    lastCommit,
    remote: remote.ok ? remote.stdout.trim() : config.remote,
    error: '',
  };
}

/** Initialize the local repository and write the selected-path excludes. */
export async function initSync(root) {
  const config = readSyncConfig(root);
  const error = requireEnabled(config);
  if (error !== '') return { ok: false, error };
  return ensureRepo(root, config);
}

/** Commit only the selected memory paths, if there is anything to commit. */
export async function commitSync(root, message = '') {
  const config = readSyncConfig(root);
  const error = requireEnabled(config);
  if (error !== '') return { ok: false, error };
  const ensured = await ensureRepo(root, config);
  if (!ensured.ok) return ensured;
  const add = await runGit(root, ['add', '-A', '--', '.']);
  if (!add.ok) return { ok: false, error: add.stderr || 'git add 失败' };
  const staged = await runGit(root, ['diff', '--cached', '--quiet']);
  if (staged.ok) return { ok: true, committed: false, message: '没有需要提交的变化' };
  const text = String(message || '').trim() || `AI for Memory sync ${new Date().toISOString()}`;
  const commit = await runGit(root, ['commit', '-m', text]);
  if (!commit.ok) return { ok: false, error: commit.stderr || 'git commit 失败' };
  return { ok: true, committed: true, message: text };
}

/** Upload: commit then push to the host remote. */
export async function pushSync(root, message = '') {
  const config = readSyncConfig(root);
  const error = requireEnabled(config);
  if (error !== '') return { ok: false, error };
  const committed = await commitSync(root, message);
  if (!committed.ok) return committed;
  const push = await runGit(root, ['push', '-u', 'origin', 'HEAD']);
  if (!push.ok) {
    return {
      ok: false,
      error: `${push.stderr || 'git push 失败'}\n如果远端已有新提交，请先拉取，不要强制覆盖。`,
    };
  }
  return { ok: true, pushed: true, committed: committed.committed, message: push.stderr.trim() };
}

/** Pull: fast-forward only. Conflicts are reported, never auto-merged. */
export async function pullSync(root) {
  const config = readSyncConfig(root);
  const error = requireEnabled(config);
  if (error !== '') return { ok: false, error };
  const ensured = await ensureRepo(root, config);
  if (!ensured.ok) return ensured;
  const fetch = await runGit(root, ['fetch', 'origin']);
  if (!fetch.ok) return { ok: false, error: fetch.stderr || 'git fetch 失败' };
  // A freshly initialized peer has no commit yet: `rev-parse HEAD` fails on an
  // unborn branch. `branch --show-current` still reports the branch name, so a
  // first pull from an empty local repo can fast-forward normally.
  const current = await runGit(root, ['branch', '--show-current']);
  const symbolic = current.ok && current.stdout.trim() !== ''
    ? current
    : await runGit(root, ['symbolic-ref', '--short', 'HEAD']);
  if (!symbolic.ok || symbolic.stdout.trim() === '') {
    return { ok: false, error: symbolic.stderr || '无法读取当前分支' };
  }
  const target = `origin/${symbolic.stdout.trim()}`;
  const merge = await runGit(root, ['merge', '--ff-only', target]);
  if (!merge.ok) {
    return {
      ok: false,
      error: `${merge.stderr || 'git merge 失败'}\n本地与主机已分叉；已停止，不会自动合并或覆盖。`,
    };
  }
  return { ok: true, pulled: true, message: merge.stdout.trim() };
}

/** Parse the Git remote forms users actually copy: URL, ssh:// and scp-like. */
export function parseGitRemote(remote) {
  const text = String(remote ?? '').trim();
  if (text === '') return null;
  try {
    const parsed = new URL(text);
    if (parsed.hostname !== '') {
      return {
        host: parsed.hostname.replace(/^\[|\]$/g, ''),
        port: parsed.port === '' ? null : Number(parsed.port),
        path: parsed.pathname,
      };
    }
  } catch {
    // Fall through to the scp-like form: git@host:path or host:path.
  }
  // Do not mistake a Windows drive path for `host:path`.
  if (/^[A-Za-z]:[\\/]/.test(text)) return null;
  const scp = /^(?:[^@\s/]+@)?(\[[^\]]+\]|[^:\s/]+):(.+)$/.exec(text);
  if (scp === null) return null;
  return {
    host: scp[1].replace(/^\[|\]$/g, ''),
    port: null,
    path: scp[2],
  };
}

/** Optional host probe: only the configured host/common ports, not a subnet scan. */
export async function probeHost(remote, connector = probePort) {
  const parsed = parseGitRemote(remote);
  if (parsed === null) {
    return {
      ok: false,
      error: 'remote 不是有效地址（支持 ssh://、https://、git:// 以及 git@host:path）',
    };
  }
  const host = parsed.host;
  if (parsed.port !== null && Number.isInteger(parsed.port) && parsed.port > 0) {
    return connector(host, parsed.port);
  }
  const ports = [22, 443, 80, 9418];
  // Probe common ports concurrently: a dead 22 must not add 3s before 443.
  const attempts = ports.map((port) => connector(host, port).then((result) => {
    if (result?.ok === true) return result;
    throw result ?? new Error(`port ${port} unreachable`);
  }));
  try {
    const result = await Promise.any(attempts);
    return { ...result, ports };
  } catch {
    return { ok: false, host, ports, error: `主机 ${host} 的常见 Git 端口均不可达` };
  }
}

function probePort(host, port) {
  return new Promise((resolve) => {
    const socket = net.createConnection({ host, port, timeout: 3000 });
    const finish = (ok, error = '') => {
      socket.destroy();
      resolve({ ok, host, port, error });
    };
    socket.once('connect', () => finish(true));
    socket.once('timeout', () => finish(false, '连接超时'));
    socket.once('error', (error) => finish(false, String(error?.message ?? error)));
  });
}
